// Типографика: превращает набранный владельцем текст в вёрстку.
//
// В разметке сайта неразрывные пробелы стоят везде, где строка не должна
// рваться: «на&nbsp;примерку», «с&nbsp;2008&nbsp;года». Требовать этого от
// владельца нельзя — он пишет обычный текст в обычном поле. Поэтому правка
// хранится чистой, а nbsp расставляются здесь, при сборке страницы.
//
// Обратная операция (plain) нужна админке: показать в поле «на примерку»,
// а не «на&nbsp;примерку».

// Короткие слова, после которых перенос строки читается как ошибка вёрстки:
// предлоги, союзы, частицы. Список закрытый — в русском их и правда столько.
// Плюс короткие местоимения: «Что мы делаем» с переносом после «мы» читается
// так же криво, как оторванный предлог, и в вёрстке сайта они тоже склеены.
const SHORT = 'а|в|во|да|для|до|же|за|и|из|к|ко|ли|на|над|не|ни|но|о|об|от|по|под|при|про|с|со|то|у|уж|через'
  + '|я|ты|мы|вы|он|она|оно|они|это';

// Единицы и слова, которые не отрываются от числа: «6 лет», «2008 года».
const AFTER_NUM = 'г|гг|год|года|лет|руб|₽|шт|см|мм|м|кг|мин|ч';

// Будущие неразрывные пробелы помечаем служебным символом и меняем на &nbsp;
// одним проходом в конце. Ставить сущность сразу нельзя: следующее правило
// искало бы пробел там, где уже стоит «&nbsp;», и половина случаев терялась бы.
const MARK = '';

// Начало слова ищем через lookbehind, а не группой захвата: с группой пробел
// перед предлогом уходит внутрь совпадения, и в цепочке «и по уровню» второй
// предлог уже не находится — разделитель съеден предыдущей заменой.
// Про \b пришлось забыть: в JS он считает словом только латиницу, и правило
// с ним не совпадало ни с «г. Нижний», ни с «на примерку».
const atWordStart = (body) => new RegExp(`(?<=^|[\\s(«"])(?:${body}) `, 'gi');
const glue = (m) => m.slice(0, -1) + MARK;

export function typo(text) {
  return String(text || '')
    .replace(/\s+/g, ' ')
    .trim()
    // предлог не должен оставаться в конце строки
    .replace(atWordStart(SHORT), glue)
    // число не отрывается от того, что считает
    .replace(new RegExp(`(\\d) (${AFTER_NUM})(?=[\\s.,;:!?)»"]|$)`, 'gi'), `$1${MARK}$2`)
    // «г. Нижний Новгород», «ул. Бетанкура» — сокращение липнет к слову
    .replace(atWordStart('г\\.|ул\\.|д\\.|стр\\.|корп\\.|оф\\.|пр\\.|пер\\.'), glue)
    // Тире не начинает строку: пробел перед ним неразрывный, после — обычный.
    .replace(/ (—|–) /g, `${MARK}$1 `)
    .replace(new RegExp(MARK, 'g'), '&nbsp;');
}

// Разметка → чистый текст для поля ввода. HTML-теги внутри абзаца
// (ссылки, выделения) остаются как есть: их немного, и убивать их правкой
// текста мы не вправе — иначе ссылка на «Условия доставки» исчезнет молча.
export function plain(html) {
  return String(html || '')
    .replace(/&nbsp;/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}
