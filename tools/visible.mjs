// Что из каталога попадает на сайт.
//
// Критерий один на всех: и меню с витриной (build-catalog.mjs), и страницы
// товаров (build-products.mjs) должны показывать ровно один и тот же набор.
// Разъедься они — в меню будет счётчик на 132 товара, а в разделе 76 карточек.
//
// Сейчас прячем товары без фотографии. Карточка без кадра — это дыра в сетке:
// плейсхолдер занимает место, но смотреть в нём нечего, и раздел из таких
// карточек читается как незагрузившаяся страница. Данные при этом никуда
// не деваются: товар остаётся в assets/products.json, скрытие снимается
// флагом ниже и повторным прогоном обоих генераторов.
//
// Раздел или подраздел, в котором не осталось ни одного видимого товара,
// исчезает сам — он нигде не перечислен руками, а собирается из этого набора.
export const HIDE_NO_PHOTO = true;

export const isVisible = (it) => !HIDE_NO_PHOTO || Boolean(it.img);

export const splitVisible = (items) => ({
  visible: items.filter(isVisible),
  hidden: items.filter((it) => !isVisible(it)),
});
